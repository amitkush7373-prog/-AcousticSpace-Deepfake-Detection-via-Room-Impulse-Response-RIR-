"""
AcousticSpace - Real Dataset Loader (Week 5 / real-data wiring)

Handles a multi-source dataset layout like:

  dataset_root/
    real_samples/        <- genuine human recordings
    FlashSpeech/          <- fake, generated by FlashSpeech TTS
    NaturalSpeech3/        <- fake, generated by NaturalSpeech3
    OpenAI/                 <- fake, generated by OpenAI TTS
    PromptTTS2/
    seedtts_files/
    VALLE/
    VoiceBox/
    xTTS/

Any folder literally named one of GENUINE_FOLDER_NAMES is treated as
genuine (label 0); every other top-level folder is treated as fake
(label 1), regardless of which generation system produced it.
"""

from __future__ import annotations

from pathlib import Path
from collections import Counter

AUDIO_EXTENSIONS = {".wav", ".mp3", ".flac", ".ogg", ".m4a"}
GENUINE_FOLDER_NAMES = {"real_samples", "real", "genuine", "bonafide"}


def discover_labeled_files(root_dir: str | Path) -> list[tuple[Path, int]]:
    root = Path(root_dir)
    if not root.exists():
        raise FileNotFoundError(f"Dataset root not found: {root}")

    samples: list[tuple[Path, int]] = []
    for subfolder in sorted(p for p in root.iterdir() if p.is_dir()):
        label = 0 if subfolder.name.lower() in GENUINE_FOLDER_NAMES else 1
        files = [
            f for f in subfolder.rglob("*")
            if f.is_file() and f.suffix.lower() in AUDIO_EXTENSIONS
        ]
        samples.extend((f, label) for f in files)

    if not samples:
        raise RuntimeError(
            f"No audio files found under {root}. Check that subfolders contain "
            f"files with extensions: {sorted(AUDIO_EXTENSIONS)}"
        )
    return samples


def summarize(samples: list[tuple[Path, int]]) -> None:
    by_source: Counter[str] = Counter()
    by_label = Counter()
    for path, label in samples:
        by_source[path.parts[-2]] += 1
        by_label[label] += 1

    print(f"Total files: {len(samples)}")
    print(f"  genuine (label 0): {by_label[0]}")
    print(f"  fake    (label 1): {by_label[1]}")
    print("Per-folder breakdown:")
    for name, count in sorted(by_source.items()):
        print(f"  {name}: {count}")


if __name__ == "__main__":
    import sys
    root = sys.argv[1] if len(sys.argv) > 1 else "data/real_dataset"
    samples = discover_labeled_files(root)
    summarize(samples)